type theoryManifest struct {
	MilestoneID string `json:"milestone_id"`
	Sections    []struct {
		ID                  string `json:"id"`
		Title               string `json:"title"`
		Content             string `json:"content"`
		IntroducedAtLevelID string `json:"introduced_at_level_id"`
	} `json:"sections"`
}

type questionsManifest struct {
	MilestoneID string `json:"milestone_id"`
	Questions   []struct {
		ID       string   `json:"id"`
		LevelID  string   `json:"level_id"`
		Question string   `json:"question"`
		Options  []string `json:"options"`
	} `json:"questions"`
}

type challengesManifest struct {
	MilestoneID string `json:"milestone_id"`
	Challenges  []struct {
		ID          string   `json:"id"`
		LevelID     string   `json:"level_id"`
		Title       string   `json:"title"`
		Description string   `json:"description"`
		Task        string   `json:"task"`
		Hints       []string `json:"hints"`
	} `json:"challenges"`
}

type referenceManifest struct {
	MilestoneID string `json:"milestone_id"`
	Language    string `json:"language"`
	Sections    []struct {
		CommonSectionID string   `json:"common_section_id"`
		SyntaxTopics    []string `json:"syntax_topics"`
		Examples        []struct {
			Title       string `json:"title"`
			Code        string `json:"code"`
			Explanation string `json:"explanation"`
		} `json:"examples"`
	} `json:"sections"`
}

type questionItem struct {
	ID       string
	LevelID  string
	Question string
	Options  []string
}

type challengeItem struct {
	ID          string
	LevelID     string
	Title       string
	Description string
	Task        string
	Hints       []string
}

// renderEducationalDocs renders the theory, language cheat sheet, graded
// knowledge checks, and guided mini-challenges generated by the Document Engine.
func renderEducationalDocs(coursePath, levelID, language string) {
	if coursePath == "" {
		return
	}

	m, idx := milestoneForLevelID(coursePath, levelID)
	if m == nil {
		ms := listMilestones(coursePath)
		if len(ms) == 0 {
			return
		}
		m = &ms[0]
		idx = -1
	}

	var sectionIDs []string
	if idx >= 0 {
		sectionIDs = m.LearningPath[idx].Unlocks.Theory
	}

	renderTheory(coursePath, *m, levelID, language, sectionIDs)
	renderKnowledgeCheck(coursePath, *m, levelID)
	renderChallenges(*m, levelID)
}

// renderMarkdown renders markdown via glamour, falling back to the raw source.
func renderMarkdown(md string) string {
	width := ui.Width()
	if width < 30 {
		width = 30
	}
	r, err := glamour.NewTermRenderer(
		glamour.WithAutoStyle(),
		glamour.WithWordWrap(width-2),
	)
	if err != nil {
		return md
	}
	out, err := r.Render(md)
	if err != nil {
		return md
	}
	return strings.TrimRight(out, "\n")
}

func renderTheory(coursePath string, m milestoneEntry, levelID, language string, sectionIDs []string) {
	data, err := os.ReadFile(filepath.Join(m.Dir, "theory.json"))
	if err != nil {
		return
	}
	var tm theoryManifest
	if err := json.Unmarshal(data, &tm); err != nil {
		return
	}

	for _, sec := range tm.Sections {
		isTarget := sec.IntroducedAtLevelID == levelID
		if !isTarget {
			for _, sid := range sectionIDs {
				if sid == sec.ID {
					isTarget = true
					break
				}
			}
		}
		if !isTarget {
			continue
		}

		ui.Println(ui.Section("📖 Core Theory — " + sec.Title))
		ui.Println(renderMarkdown(sec.Content))

		if language != "" {
			renderReference(coursePath, m, language, sec.ID)
		}
		break
	}
}

func renderReference(coursePath string, m milestoneEntry, language, sectionID string) {
	refPath := filepath.Join(coursePath, "languages", language, "milestones", m.Base, "reference.json")
	data, err := os.ReadFile(refPath)
	if err != nil {
		return
	}
	var rm referenceManifest
	if err := json.Unmarshal(data, &rm); err != nil {
		return
	}

	for _, rsec := range rm.Sections {
		if rsec.CommonSectionID != sectionID {
			continue
		}
		if len(rsec.SyntaxTopics) > 0 {
			ui.Println(ui.InfoStyle.Render("💻 Syntax & APIs: ") + strings.Join(rsec.SyntaxTopics, ", "))
		}
		for _, ex := range rsec.Examples {
			var b strings.Builder
			fmt.Fprintf(&b, "#### Reference Example — %s\n\n", ex.Title)
			fmt.Fprintf(&b, "```%s\n%s\n```\n", language, ex.Code)
			if ex.Explanation != "" {
				fmt.Fprintf(&b, "\n> 💡 %s\n", ex.Explanation)
			}
			ui.Println(renderMarkdown(b.String()))
		}
		break
	}
}

func renderKnowledgeCheck(coursePath string, m milestoneEntry, levelID string) {
	data, err := os.ReadFile(filepath.Join(m.Dir, "questions.json"))
	if err != nil {
		return
	}
	var qm questionsManifest
	if err := json.Unmarshal(data, &qm); err != nil {
		return
	}

	var questions []questionItem
	for _, q := range qm.Questions {
		if q.LevelID == levelID {
			questions = append(questions, questionItem{q.ID, q.LevelID, q.Question, q.Options})
		}
	}
	if len(questions) == 0 {
		return
	}

	ui.Println(ui.Section("🧩 Interactive Knowledge Check"))

	solutions := loadSolutions(coursePath, m.Base)

	if ui.Interactive() {
		runKnowledgeCheck(questions, solutions)
		return
	}

	for _, q := range questions {
		ui.Println(ui.BoldStyle.Render("[Q] " + q.Question))
		for i, opt := range q.Options {
			ui.Printf("      %d) %s\n", i+1, opt)
		}
		ui.Println()
	}
	ui.Println(ui.MutedStyle.Render("(run in an interactive terminal to answer and verify)"))
}

// evaluateMCQs grades recorded answer indices against the answer key. It is a
// pure function so the 100% pass rule is unit-testable. When a question has no
// answer key it cannot be graded and is excluded from the score.
func evaluateMCQs(questions []questionItem, solutions map[string]solutionQuestion, answers map[string]int) (correct, total int, passed bool) {
	for _, q := range questions {
		sol, ok := solutions[q.ID]
		if !ok {
			continue
		}
		got, answered := answers[q.ID]
		total++
		if answered && got == sol.AnswerIndex {
			correct++
		}
	}
	return correct, total, total > 0 && correct == total
}

// runKnowledgeCheck grades the quiz and only reports success at 100%. It offers
// retries until the learner clears every question.
func runKnowledgeCheck(questions []questionItem, solutions map[string]solutionQuestion) bool {
	gated := false
	for _, q := range questions {
		if _, ok := solutions[q.ID]; ok {
			gated = true
			break
		}
	}

	for {
		answers := map[string]int{}
		for _, q := range questions {
			ui.Println("\n" + ui.BoldStyle.Render("[Q] "+q.Question))

			choice, err := ui.Select("Choose your answer", q.Options)
			if err != nil {
				ui.Println(ui.WarnStyle.Render("Interactive prompt unavailable; skipping grading."))
				return false
			}
			answers[q.ID] = choice

			sol, hasKey := solutions[q.ID]
			if !hasKey {
				ui.Println(ui.MutedStyle.Render(fmt.Sprintf("  Recorded option %d. (No local answer key available.)", choice+1)))
				continue
			}

			if choice == sol.AnswerIndex {
				ui.Println(ui.SuccessStyle.Render("  ✅ Correct!"))
			} else {
				ui.Println(ui.DangerStyle.Render(fmt.Sprintf("  ❌ Incorrect — correct answer: %d) %s",
					sol.AnswerIndex+1, q.Options[sol.AnswerIndex])))
			}
			if sol.Explanation != "" {
				ui.Println(ui.HintStyle.Render("💡 " + sol.Explanation))
			}
		}

		if !gated {
			return true
		}

		correct, total, passed := evaluateMCQs(questions, solutions, answers)
		if passed {
			ui.Println("\n" + ui.Success(fmt.Sprintf("KNOWLEDGE CHECK PASSED — %d/%d (100%%)", correct, total)))
			return true
		}

		ui.Println("\n" + ui.Danger(fmt.Sprintf("NOT PASSED — %d/%d. A 100%% score is required.", correct, total)))
		retry, err := ui.Confirm("Retry the knowledge check now?", "Retry", "Later")
		if err != nil || !retry {
			return false
		}
	}
}

func renderChallenges(m milestoneEntry, levelID string) {
	data, err := os.ReadFile(filepath.Join(m.Dir, "challenges.json"))
	if err != nil {
		return
	}
	var cm challengesManifest
	if err := json.Unmarshal(data, &cm); err != nil {
		return
	}

	var challenges []challengeItem
	for _, ch := range cm.Challenges {
		if ch.LevelID == levelID {
			challenges = append(challenges, challengeItem{ch.ID, ch.LevelID, ch.Title, ch.Description, ch.Task, ch.Hints})
		}
	}
	if len(challenges) == 0 {
		return
	}

	ui.Println(ui.Section("🛠️  Interactive Mini-Challenges"))

	if !ui.Interactive() {
		for _, ch := range challenges {
			printChallengeStatic(ch)
		}
		return
	}

	completed := 0
	for _, ch := range challenges {
		if runChallenge(ch) {
			completed++
		}
	}

	if completed == len(challenges) {
		ui.Println(ui.Success(fmt.Sprintf("ALL CHALLENGES COMPLETE — %d/%d (100%%)", completed, len(challenges))))
	} else {
		ui.Println(ui.WarnStyle.Render(fmt.Sprintf("Challenges completed: %d/%d — finish them all to reach 100%%.", completed, len(challenges))))
	}
}

func printChallengeStatic(ch challengeItem) {
	ui.Println("  " + ui.BoldStyle.Render("• "+ch.Title))
	ui.Println("    " + ui.Wrap(ch.Description))
	ui.Println("    " + ui.InfoStyle.Render("Task: ") + ui.Wrap(ch.Task))
	for _, h := range ch.Hints {
		ui.Println("      " + ui.MutedStyle.Render("- "+h))
	}
	ui.Println()
}

func runChallenge(ch challengeItem) bool {
	ui.Println("\n" + ui.PanelStyle.Width(ui.Width()-2).Render(
		ui.BoldStyle.Render(ch.Title)+"\n"+
			ui.MutedStyle.Render(ch.Description)+"\n\n"+
			ui.InfoStyle.Render("Task: ")+ch.Task,
	))

	revealed := 0
	for {
		options := []string{}
		if revealed < len(ch.Hints) {
			options = append(options, fmt.Sprintf("Reveal hint %d of %d", revealed+1, len(ch.Hints)))
		}
		options = append(options, "Mark as complete", "Skip for now")

		choice, err := ui.Select("What next?", options)
		if err != nil {
			return false
		}

		label := options[choice]
		switch {
		case strings.HasPrefix(label, "Reveal hint"):
			ui.Println(ui.HintStyle.Render("💡 " + ch.Hints[revealed]))
			revealed++
		case label == "Mark as complete":
			ui.Println(ui.SuccessStyle.Render("  ✅ Marked complete: " + ch.Title))
			return true
		default:
			ui.Println(ui.MutedStyle.Render("  ↩ Skipped: " + ch.Title))
			return false
		}
	}
}
