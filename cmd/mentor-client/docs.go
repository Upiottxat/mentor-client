package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type theoryManifest struct {
	MilestoneID string `json:"milestone_id"`
	Sections    []struct {
		ID                  string `json:"id"`
		Title               string `json:"title"`
		Content             string `json:"content"`
		IntroducedAtLevelID string `json:"introduced_at_level_id"`
	} `json:"sections"`
}

type questionsManifest struct {
	MilestoneID string `json:"milestone_id"`
	Questions   []struct {
		ID       string   `json:"id"`
		LevelID  string   `json:"level_id"`
		Question string   `json:"question"`
		Options  []string `json:"options"`
	} `json:"questions"`
}

type challengesManifest struct {
	MilestoneID string `json:"milestone_id"`
	Challenges  []struct {
		ID          string   `json:"id"`
		LevelID     string   `json:"level_id"`
		Title       string   `json:"title"`
		Description string   `json:"description"`
		Task        string   `json:"task"`
		Hints       []string `json:"hints"`
	} `json:"challenges"`
}

type referenceManifest struct {
	MilestoneID string `json:"milestone_id"`
	Language    string `json:"language"`
	Sections    []struct {
		CommonSectionID string   `json:"common_section_id"`
		SyntaxTopics    []string `json:"syntax_topics"`
		Examples        []struct {
			Title       string `json:"title"`
			Code        string `json:"code"`
			Explanation string `json:"explanation"`
		} `json:"examples"`
	} `json:"sections"`
}

// renderEducationalDocs renders the rich study guide, language cheat sheet,
// concept MCQs, and mini-challenges generated by the Document Engine.
func renderEducationalDocs(coursePath string, levelID string, language string) {
	if coursePath == "" || levelID == "" {
		return
	}

	milestonesDir := filepath.Join(coursePath, "common", "milestones")
	entries, err := os.ReadDir(milestonesDir)
	if err != nil {
		return
	}

	var matchedMilestoneDir string
	var matchedSectionIDs []string

	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		mPath := filepath.Join(milestonesDir, entry.Name())
		manifestFile := filepath.Join(mPath, "manifest.json")
		data, err := os.ReadFile(manifestFile)
		if err != nil {
			continue
		}

		var mf struct {
			LearningPath []struct {
				LevelID string `json:"level_id"`
				Unlocks struct {
					Theory []string `json:"theory"`
				} `json:"unlocks"`
			} `json:"learning_path"`
		}
		if err := json.Unmarshal(data, &mf); err == nil {
			for _, lp := range mf.LearningPath {
				if lp.LevelID == levelID {
					matchedMilestoneDir = mPath
					matchedSectionIDs = lp.Unlocks.Theory
					break
				}
			}
		}
		if matchedMilestoneDir != "" {
			break
		}
	}

	// If no manifest match, fall back to searching all milestones
	if matchedMilestoneDir == "" && len(entries) > 0 {
		for _, entry := range entries {
			if entry.IsDir() {
				matchedMilestoneDir = filepath.Join(milestonesDir, entry.Name())
				break
			}
		}
	}

	if matchedMilestoneDir == "" {
		return
	}

	milestoneBaseName := filepath.Base(matchedMilestoneDir)

	// 1. Render Core Concept & Theory
	theoryPath := filepath.Join(matchedMilestoneDir, "theory.json")
	if data, err := os.ReadFile(theoryPath); err == nil {
		var tm theoryManifest
		if err := json.Unmarshal(data, &tm); err == nil {
			for _, sec := range tm.Sections {
				isTarget := sec.IntroducedAtLevelID == levelID
				if !isTarget && len(matchedSectionIDs) > 0 {
					for _, sid := range matchedSectionIDs {
						if sid == sec.ID {
							isTarget = true
							break
						}
					}
				}

				if isTarget {
					fmt.Printf("%s📖 CORE THEORY & CONCEPTS (%s):%s\n", colorBold, sec.Title, colorReset)
					fmt.Printf("%s\n\n", sec.Content)

					// 2. Render Language Reference / Syntax Guide if available
					if language != "" {
						refPath := filepath.Join(coursePath, "languages", language, "milestones", milestoneBaseName, "reference.json")
						if rdata, err := os.ReadFile(refPath); err == nil {
							var rm referenceManifest
							if err := json.Unmarshal(rdata, &rm); err == nil {
								for _, rsec := range rm.Sections {
									if rsec.CommonSectionID == sec.ID {
										if len(rsec.SyntaxTopics) > 0 {
											fmt.Printf("%s💻 Syntax & APIs:%s %s\n", colorBold, colorReset, strings.Join(rsec.SyntaxTopics, ", "))
										}
										for _, ex := range rsec.Examples {
											fmt.Printf("\n%sReference Example — %s:%s\n", colorCyan, ex.Title, colorReset)
											for _, line := range strings.Split(ex.Code, "\n") {
												fmt.Printf("   %s\n", line)
											}
											if ex.Explanation != "" {
												fmt.Printf("   %s💡 %s%s\n", colorYellow, ex.Explanation, colorReset)
											}
										}
										fmt.Println()
										break
									}
								}
							}
						}
					}
					break
				}
			}
		}
	}

	// 3. Render Interactive Knowledge Check (MCQ)
	questionsPath := filepath.Join(matchedMilestoneDir, "questions.json")
	if data, err := os.ReadFile(questionsPath); err == nil {
		var qm questionsManifest
		if err := json.Unmarshal(data, &qm); err == nil {
			first := true
			for _, q := range qm.Questions {
				if q.LevelID == levelID {
					if first {
						fmt.Printf("%s🧩 INTERACTIVE KNOWLEDGE CHECK:%s\n", colorBold, colorReset)
						first = false
					}
					fmt.Printf("  [Q] %s\n", q.Question)
					for i, opt := range q.Options {
						fmt.Printf("      %d) %s\n", i+1, opt)
					}
					fmt.Println()
				}
			}
		}
	}

	// 4. Render Interactive Mini-Challenges
	challengesPath := filepath.Join(matchedMilestoneDir, "challenges.json")
	if data, err := os.ReadFile(challengesPath); err == nil {
		var cm challengesManifest
		if err := json.Unmarshal(data, &cm); err == nil {
			first := true
			for _, ch := range cm.Challenges {
				if ch.LevelID == levelID {
					if first {
						fmt.Printf("%s🛠️ INTERACTIVE MINI-CHALLENGE:%s\n", colorBold, colorReset)
						first = false
					}
					fmt.Printf("  • %s%s%s: %s\n", colorBold, ch.Title, colorReset, ch.Description)
					fmt.Printf("    Task: %s\n", ch.Task)
					if len(ch.Hints) > 0 {
						fmt.Printf("    Hints:\n")
						for _, h := range ch.Hints {
							fmt.Printf("      - %s\n", h)
						}
					}
					fmt.Println()
				}
			}
		}
	}
}
